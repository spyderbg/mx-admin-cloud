"""The single Git mutation coordinator for the shared checkout (v5 §3.3).

Agents never run mutating Git commands. Every mutation goes through GitCoordinator,
serialized by git.lock; operations that change the working tree (creating/switching the
feature branch) additionally need project.lock EXCLUSIVE, i.e. no scoped writer active.

Role-scoped commits never touch the shared index while building the commit and never
read another role's files:

  1. under git.lock, verify the checkout is on the feature branch;
  2. validate every manifest path against the role's write scope (deny-by-default);
  3. refuse if the shared index already holds staged content (foreign changes);
  4. if HEAD moved since the request was prepared, continue only when the new commits
     are descendants and touch none of the manifest paths (disjoint parallel work);
  5. verify each file still has the SHA-256 the worker declared (stability);
  6. build the tree in a PRIVATE index (`GIT_INDEX_FILE`): read-tree HEAD, then add or
     remove exactly the manifest paths — nothing else from the working tree can enter;
  7. re-read the staged blobs and compare them with the declared hashes again;
  8. `commit-tree`, then `update-ref <branch> <new> <old>` (atomic compare-and-swap);
  9. refresh only those paths in the shared index so `git status` stays truthful.

The commit message is generated by the coordinator, never by an agent: a short subject from
trusted task data (`commit_subject`: the task title when it is a short one-line summary, else
`<role>: task <task id>`, so a task's instruction text never becomes a subject), then the
`Feature:`, `Feature-Task:` and `Feature-Role:` trailers.

W3 checkpoints add a `Feature-Checkpoint: <checkpoint id>` trailer. The id is unique (it
carries a random part recorded in the state store before the commit), so the commit of a
checkpoint can be found again after a crash. Committing a checkpoint is idempotent: under
git.lock, a request whose checkpoint id already has a commit on the branch (since the expected
HEAD) returns that commit (`CommitResult.existing`) instead of creating a second one.

Plumbing commands run no hooks. `push_plan` renders the push as a dry-run plan (Phases 2–3).

W4.3.3 (publish.py, an approved GitHub Issue's feature only): `push_branch` pushes EXACTLY the validated
commit to the remote's refs/heads/<feature branch> — never a protected branch, never forced (a remote
branch that the commit does not contain is refused), only from a clean checkout that is on that branch
at that commit, under project.lock EXCLUSIVE + git.lock, with no hooks and a bounded time. Under those
locks, before reading the remote and again right before the push, the remote must have exactly one
configured URL and exactly one effective push URL, both the approved destination: `git push <remote>`
publishes to EVERY push URL (all `pushurl` values, else all `url` values, after insteadOf/pushInsteadOf
rewriting). It reads the remote branch first and after, so a repeated or interrupted push is safe.
`fetch_branch` fetches one branch (merge verification) into FETCH_HEAD; no local branch or working-tree
file changes.

Revalidation of a changed PR head (revalidate.py): `fast_forward_branch` moves the checked-out feature branch
FORWARD to a fetched commit that contains it (`git merge --ff-only`, hooks off, the repository's own execution
config refused) — never a reset, never a non-fast-forward — under project.lock EXCLUSIVE (held by the caller,
which runs the gates under it) + git.lock. Nothing is pushed.
"""

