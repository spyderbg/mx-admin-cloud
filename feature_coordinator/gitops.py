# gitsafe: also drop the config-injecting / program-naming Git variables (and the KEY_*/VALUE_* prefixes).
_SCRUBBED_ENV = extend_scrub(("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_OBJECT_DIRECTORY", "GIT_COMMON_DIR"))
COMMIT_SUBJECT_MAX = 72
CHECKPOINT_TRAILER = "Feature-Checkpoint"
_SHA_RE = re.compile(r"[0-9a-f]{40}")
_FEATURE_REF_RE = re.compile(r"feature/[a-z0-9][a-z0-9._-]{0,99}")  # W4.3.3: the only branches ever pushed
_BRANCH_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9._/-]{0,99}")


@dataclass(frozen=True)
class PushResult:
    """W4.3.3: the remote's refs/heads/<branch> is now `sha` (`pushed` False: it already was — a repeat)."""

    branch: str
    sha: str
    before: str | None  # the remote branch before the push (None: it did not exist)
    pushed: bool


def _tail(result: subprocess.CompletedProcess[str]) -> str:
    return " ".join((result.stderr or result.stdout or "").split())[-300:]


def commit_subject(role: str, task_id: str, title: str) -> str:
    """The subject of a task's role-scoped commit: `<role>: <title>` when the task title is one
    printable line that fits COMMIT_SUBJECT_MAX (whitespace collapsed); otherwise — a multi-line
    or long title, typically the task's whole instruction — the deterministic `<role>: task <task id>`."""
    lines = (title or "").strip().splitlines()
    if len(lines) == 1:
        summary = " ".join(lines[0].split())
        subject = f"{role}: {summary}"
        if summary.isprintable() and len(subject) <= COMMIT_SUBJECT_MAX:
            return subject
    return f"{role}: task {task_id}"


def file_digest(path: Path) -> str | None:
    """SHA-256 of a file's bytes, or None if it does not exist."""
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except FileNotFoundError:
        return None


@dataclass(frozen=True)
class CommitRequest:
    """A role-scoped commit: an explicit manifest with the content hash of each file
    (None = the file is deleted), the HEAD the worker last saw, and task identity."""

    feature_id: str
    task_id: str
    role: str
    branch: str
    expected_head: str
    files: Mapping[str, str | None]
    message: str
    grants: tuple[str, ...] = ()
    checkpoint_id: str = ""  # W3: adds the Feature-Checkpoint trailer; makes the commit idempotent


@dataclass(frozen=True)
class CommitResult:
    """A landed commit (or, with `existing`, the checkpoint commit that was already there)."""

    sha: str
    parent: str
    paths: tuple[str, ...]
    moved_over: tuple[str, ...] = field(default_factory=tuple)
    existing: bool = False


def branch_contains(repo: Path, branch: str, sha: str, *, env: Mapping[str, str] | None = None) -> bool:
    """True when commit *sha* is an ancestor of (or equal to) refs/heads/<branch> in *repo*."""
    if not re.fullmatch(r"[0-9a-f]{7,40}", sha):
        return False
    result = subprocess.run(["git", "-C", str(repo), *SAFE_CONFIG_ARGS, "merge-base", "--is-ancestor", sha,
                             f"refs/heads/{branch}"], capture_output=True, text=True,
                            env=None if env is None else dict(env), check=False)
    return result.returncode == 0


class GitCoordinator:  # pylint: disable=too-many-public-methods
    """Serialized Git mutations for one checkout."""

    def __init__(self, repo_root: Path, locks: LockSet, policy: PathPolicy, *, tmp_dir: Path,
                 lock_timeout: float = 30.0) -> None:
        self.root = Path(repo_root)
        self.locks = locks
        self.policy = policy
        self.tmp_dir = tmp_dir
        self.lock_timeout = lock_timeout

    # -- process helpers -----------------------------------------------------

    def _env(self, extra: Mapping[str, str] | None = None) -> dict[str, str]:
        env = {k: v for k, v in os.environ.items()
               if k not in _SCRUBBED_ENV and not k.startswith(tuple(scrub_prefixes()))}
        env.update({"LC_ALL": "C", "GIT_TERMINAL_PROMPT": "0", "GIT_OPTIONAL_LOCKS": "0"})
        env.update(extra or {})
        return env

    def _gitc(self) -> list[str]:
        """`git -C <root>` with the gitsafe -c overrides — the prefix of every Coordinator Git call."""
        return ["git", "-C", str(self.root), *SAFE_CONFIG_ARGS]

    def _git(self, *args: str, env: Mapping[str, str] | None = None, check: bool = True) -> str:
        result = subprocess.run([*self._gitc(), *args], capture_output=True, text=True,
                                env=self._env(env), check=False)
        if check and result.returncode != 0:
            detail = result.stderr.strip() or result.stdout.strip()
            raise GitOperationError(f"git {' '.join(args[:2])} failed: {detail}")
        return result.stdout

    def _git_bytes(self, *args: str, env: Mapping[str, str] | None = None) -> bytes:
        result = subprocess.run([*self._gitc(), *args], capture_output=True, env=self._env(env),
                                check=False)
        if result.returncode != 0:
            raise GitOperationError(f"git {' '.join(args[:2])} failed: {result.stderr.decode(errors='replace')}")
        return result.stdout

    # -- read-only queries (safe without locks) ------------------------------

    def current_branch(self) -> str | None:
        """The checked-out branch, or None when HEAD is detached."""
        out = self._git("symbolic-ref", "--quiet", "--short", "HEAD", check=False).strip()
        return out or None

    def rev_parse(self, ref: str) -> str:
        """Full SHA of *ref*."""
        return self._git("rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}").strip()

    def contains(self, branch: str, sha: str) -> bool:
        """True when commit *sha* is on *branch* (read-only; no lock needed)."""
        return branch_contains(self.root, branch, sha, env=self._env())

    def branch_exists(self, branch: str) -> bool:
        """True if refs/heads/<branch> exists."""
        result = subprocess.run([*self._gitc(), "show-ref", "--verify", "--quiet",
                                 f"refs/heads/{branch}"], env=self._env(), check=False)
        return result.returncode == 0

    def staged_paths(self) -> list[str]:
        """Paths with staged changes in the shared index."""
        out = self._git("diff", "--cached", "--name-only", "-z")
        return [p for p in out.split("\0") if p]

    def tracked_changes(self) -> list[str]:
        """Tracked files modified in the working tree or index (untracked files ignored)."""
        out = self._git("status", "--porcelain=v1", "-z", "--untracked-files=no")
        return [entry[3:] for entry in out.split("\0") if entry]

    def untracked_files(self) -> list[str]:
        """Untracked, not ignored files in the working tree."""
        out = self._git("ls-files", "--others", "--exclude-standard", "-z")
        return [p for p in out.split("\0") if p]

    def changed_paths(self, base: str, head: str) -> list[str]:
        """Paths changed between two commits."""
        out = self._git("diff", "--name-only", "-z", f"{base}..{head}")
        return [p for p in out.split("\0") if p]

    def commits_between(self, base: str, head: str) -> list[str]:
        """Commits reachable from *head* but not *base*, oldest first (read-only)."""
        return self._git("rev-list", "--reverse", f"{base}..{head}").split()

    def merge_commits(self, base: str, head: str) -> list[str]:
        """The merge commits among `commits_between(base, head)` (read-only)."""
        return self._git("rev-list", "--merges", f"{base}..{head}").split()

    def touched_paths(self, base: str, head: str) -> list[str]:
        """Every path added, changed or removed between two commits — both sides of a rename (read-only)."""
        out = self._git("diff", "--no-renames", "--name-only", "-z", f"{base}..{head}")
        return [p for p in out.split("\0") if p]

    def has_commit(self, sha: str) -> bool:
        """True when the commit object *sha* is in the local repository (read-only)."""
        return self._has_commit(sha)

    def is_ancestor(self, ancestor: str, descendant: str) -> bool:
        """True when *ancestor* is an ancestor of (or equal to) *descendant* (read-only)."""
        result = subprocess.run([*self._gitc(), "merge-base", "--is-ancestor", ancestor, descendant],
                                capture_output=True, env=self._env(), check=False)
        return result.returncode == 0

    def trailers(self, sha: str) -> dict[str, list[str]]:
        """The trailers of commit *sha*: key → values (read-only)."""
        found: dict[str, list[str]] = {}
        for line in self._git("log", "-1", "--format=%(trailers:only,unfold)", sha).splitlines():
            key, sep, value = line.partition(":")
            if sep:
                found.setdefault(key.strip(), []).append(value.strip())
        return found

    def checkpoint_commits(self, rev_range: str) -> dict[str, list[str]]:
        """W3: checkpoint id → commits carrying it in *rev_range* (e.g. `base..branch`), read-only.
        More than one commit for an id is reported by the caller as an inconsistency."""
        out = self._git("log", f"--format=%H%x1f%(trailers:key={CHECKPOINT_TRAILER},valueonly,separator=%x1d)%x1e",
                        rev_range)
        found: dict[str, list[str]] = {}
        for entry in out.split("\x1e"):
            sha, _sep, values = entry.strip().partition("\x1f")
            for value in (v.strip() for v in values.split("\x1d")):
                if sha and value:
                    found.setdefault(value, []).append(sha)
        return found

    def blob_digest(self, sha: str, path: str) -> str | None:
        """SHA-256 of *path* in commit *sha*, or None when the commit has no such file (read-only)."""
        result = subprocess.run([*self._gitc(), "cat-file", "blob", f"{sha}:{path}"],
                                capture_output=True, env=self._env(), check=False)
        return hashlib.sha256(result.stdout).hexdigest() if result.returncode == 0 else None

    # -- working-tree-changing operations (need quiescence) ------------------

    def _quiescent(self):
        try:
            return self.locks.project(shared=False, busy_error=WritersActiveError).acquire()
        except WritersActiveError as exc:
            raise WritersActiveError("branch operations change the working tree and require every writer "
                                     "to be quiescent; scoped writers are active") from exc

    def create_feature_branch(self, branch: str, base_ref: str) -> str:
        """Create *branch* at *base_ref* and check it out. Returns the base SHA."""
        project = self._quiescent()
        try:
            with self.locks.git().acquire(timeout=self.lock_timeout):
                if self.branch_exists(branch):
                    raise GitOperationError(f"branch {branch!r} already exists; one branch per feature")
                if self.tracked_changes():
                    raise GitOperationError("the shared checkout has uncommitted tracked changes")
                base_sha = self.rev_parse(base_ref)
                self._git("branch", "--no-track", branch, base_sha)
                self._git("switch", "--quiet", branch)
                return base_sha
        finally:
            project.release()

    def switch_branch(self, branch: str) -> None:
        """Check out an existing branch — refused while any scoped writer is active."""
        project = self._quiescent()
        try:
            with self.locks.git().acquire(timeout=self.lock_timeout):
                if self.tracked_changes():
                    raise GitOperationError("the shared checkout has uncommitted tracked changes")
                self._git("switch", "--quiet", branch)
        finally:
            project.release()

    # -- role-scoped commits -------------------------------------------------

    def commit(self, request: CommitRequest, *, author: tuple[str, str] | None = None) -> CommitResult:
        """Land a role-scoped commit on the feature branch. See the module docstring."""
        with self.locks.git().acquire(timeout=self.lock_timeout):
            # gitsafe: never build or land a commit while the checkout's own Git config could run a
            # program (an agent may have written .git/config during the run). Fail closed.
            assert_no_execution_config(self.root, where="the feature checkout")
            if self.current_branch() != request.branch:
                raise HeadMismatchError(f"checkout is on {self.current_branch()!r}, not {request.branch!r}")
            head = self.rev_parse(f"refs/heads/{request.branch}")
            if request.checkpoint_id:
                existing = self.checkpoint_commits(f"{request.expected_head}..{head}").get(request.checkpoint_id)
                if existing:  # a repeated checkpoint commit: never a second commit for the same id
                    sha = existing[-1]
                    return CommitResult(sha=sha, parent=self.rev_parse(f"{sha}^"), paths=(), existing=True)
            normalized = self.policy.require(request.role, request.files, grants=request.grants)
            declared = self._declared_hashes(request)
            if self.staged_paths():
                raise ForeignStagedContentError(f"the shared index has staged content {self.staged_paths()}; "
                                                "refusing to commit around it")
            moved_over = self._check_head(request.expected_head, head, normalized)
            self._check_stable(declared)
            tree = self._build_tree(head, declared)
            if tree == self._git("rev-parse", f"{head}^{{tree}}").strip():
                raise NothingToCommitError(f"{list(declared)} already match {head[:12]}")
            self._check_staged_blobs(tree, declared)
            commit_env = {}
            if author:
                name, email = author
                commit_env = {"GIT_AUTHOR_NAME": name, "GIT_AUTHOR_EMAIL": email,
                              "GIT_COMMITTER_NAME": name, "GIT_COMMITTER_EMAIL": email}
            message = (f"{request.message.strip()}\n\nFeature: {request.feature_id}\n"
                       f"Feature-Task: {request.task_id}\nFeature-Role: {request.role}\n")
            if request.checkpoint_id:
                message += f"{CHECKPOINT_TRAILER}: {request.checkpoint_id}\n"
            sha = self._commit_tree(tree, head, message, commit_env)
            result = subprocess.run(
                [*self._gitc(), "update-ref", "-m", f"feature-coordinator: {request.task_id}",
                 f"refs/heads/{request.branch}", sha, head],
                capture_output=True, text=True, env=self._env(), check=False)
            if result.returncode != 0:
                raise HeadMismatchError(f"branch moved during the commit (compare-and-swap failed): {result.stderr}")
            self._refresh_index(list(declared))
            return CommitResult(sha=sha, parent=head, paths=tuple(declared), moved_over=moved_over)

    def _declared_hashes(self, request: CommitRequest) -> dict[str, str | None]:
        declared: dict[str, str | None] = {}
        for raw, digest in request.files.items():
            rel = self.policy.normalize(raw)[0]
            if digest is not None and (len(digest) != 64 or any(c not in "0123456789abcdef" for c in digest)):
                raise GitOperationError(f"manifest entry {raw!r} needs a SHA-256 hex digest or None")
            declared[rel] = digest
        if not declared:
            raise NothingToCommitError("empty manifest")
        return declared

    def _check_head(self, expected: str, head: str, paths: Sequence[str]) -> tuple[str, ...]:
        if expected == head:
            return ()
        ancestor = subprocess.run([*self._gitc(), "merge-base", "--is-ancestor", expected, head],
                                  env=self._env(), check=False)
        if ancestor.returncode != 0:
            raise HeadMismatchError(f"expected HEAD {expected[:12]} is not an ancestor of {head[:12]}")
        touched = [p for p in self._git("diff", "--name-only", "-z", expected, head, "--", *paths).split("\0") if p]
        if touched:
            raise HeadMismatchError(f"{touched} changed on the branch since {expected[:12]}; rebase the work first")
        return tuple(self._git("rev-list", "--reverse", f"{expected}..{head}").split())

    def _check_stable(self, declared: Mapping[str, str | None]) -> None:
        changed = [p for p, digest in declared.items() if file_digest(self.root / p) != digest]
        if changed:
            raise UnstableFileError(f"{changed} differ from the declared content; resubmit when stable")

    def _build_tree(self, head: str, declared: Mapping[str, str | None]) -> str:
        self.tmp_dir.mkdir(parents=True, exist_ok=True)
        fd, index_path = tempfile.mkstemp(prefix="git-index-", dir=self.tmp_dir)
        os.close(fd)
        os.unlink(index_path)  # git creates the index file itself
        env = {"GIT_INDEX_FILE": index_path}
        try:
            self._git("read-tree", head, env=env)
            present = [p for p, digest in declared.items() if digest is not None]
            removed = [p for p, digest in declared.items() if digest is None]
            if present:
                self._git("update-index", "--add", "--", *present, env=env)
            if removed:
                self._git("update-index", "--force-remove", "--", *removed, env=env)
            return self._git("write-tree", env=env).strip()
        finally:
            Path(index_path).unlink(missing_ok=True)

    def _check_staged_blobs(self, tree: str, declared: Mapping[str, str | None]) -> None:
        for path, digest in declared.items():
            if digest is None:
                continue
            blob = self._git_bytes("cat-file", "blob", f"{tree}:{path}")
            if hashlib.sha256(blob).hexdigest() != digest:
                raise UnstableFileError(f"{path!r} changed while it was being staged; resubmit when stable")

    def _commit_tree(self, tree: str, parent: str, message: str, env: Mapping[str, str]) -> str:
        result = subprocess.run([*self._gitc(), "commit-tree", tree, "-p", parent],
                                input=message, capture_output=True, text=True, env=self._env(env), check=False)
        if result.returncode != 0:
            raise GitOperationError(f"git commit-tree failed: {result.stderr.strip()}")
        return result.stdout.strip()

    def _refresh_index(self, paths: Sequence[str], attempts: int = 5) -> None:
        for attempt in range(attempts):
            result = subprocess.run([*self._gitc(), "reset", "-q", "HEAD", "--", *paths],
                                    capture_output=True, text=True, env=self._env(), check=False)
            if result.returncode == 0:
                return
            if "index.lock" not in result.stderr or attempt == attempts - 1:
                raise GitOperationError(f"commit landed but refreshing the index failed: {result.stderr.strip()}")
            time.sleep(0.1 * (attempt + 1))

    # -- remote operations (W4.3.3; see the module docstring) -----------------

    def remote_urls(self, remote: str = "origin") -> tuple[tuple[str, ...], tuple[str, ...]]:
        """(every configured remote.<remote>.url, EVERY URL a push to *remote* publishes to). A push goes to all
        of them — each pushurl, else each url — after insteadOf/pushInsteadOf rewriting; without --all,
        `get-url --push` shows only the first."""
        def lines(*args: str) -> tuple[str, ...]:
            return tuple(line.strip() for line in self._git(*args, check=False).splitlines() if line.strip())
        return (lines("config", "--get-all", f"remote.{remote}.url"),
                lines("remote", "get-url", "--push", "--all", remote))

    def _check_destination(self, remote: str, destination: str) -> None:
        """(Under git.lock) a push to *remote* publishes to *destination* and nowhere else."""
        configured, push = self.remote_urls(remote)
        if configured != (destination,) or push != (destination,):
            raise ScopeViolationError(f"a push to {remote} would publish to {len(push)} URL(s) ({len(configured)} "
                                      "configured), not exactly the approved destination; nothing is pushed")

    def _network(self, *args: str, timeout: float) -> subprocess.CompletedProcess[str]:
        """A git command that talks to a remote: no hooks, no prompts, bounded. On timeout the whole process
        group is killed (RemoteUnavailableError: the operation may still have reached the remote)."""
        proc = subprocess.Popen([*self._gitc(), *args],  # pylint: disable=consider-using-with
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE, stdin=subprocess.DEVNULL, text=True,
                                env=self._env(), start_new_session=True)
        try:
            out, err = proc.communicate(timeout=timeout)
        except subprocess.TimeoutExpired:
            try:
                os.killpg(proc.pid, signal.SIGKILL)
            except (ProcessLookupError, PermissionError):
                proc.kill()
            proc.communicate()
            raise RemoteUnavailableError(f"git {args[0]} did not finish within {timeout:.0f}s (it may have reached "
                                         "the remote; the next attempt reads the remote first)") from None
        return subprocess.CompletedProcess(proc.args, proc.returncode, out, err)

    def remote_head(self, branch: str, *, remote: str = "origin", timeout: float = 120.0) -> str | None:
        """The commit of refs/heads/<branch> on *remote* (None: the remote has no such branch). Read-only."""
        ref = f"refs/heads/{branch}"
        result = self._network("ls-remote", "--heads", remote, ref, timeout=timeout)
        if result.returncode != 0:
            raise RemoteUnavailableError(f"git ls-remote {remote} failed: {_tail(result)}")
        for line in result.stdout.splitlines():
            sha, _sep, name = line.partition("\t")
            if name.strip() == ref and _SHA_RE.fullmatch(sha):
                return sha
        return None

    def push_branch(self, branch: str, sha: str, *, destination: str, protected: Sequence[str] = (),
                    remote: str = "origin", timeout: float = 120.0) -> PushResult:
        """Push exactly *sha* to *remote*'s refs/heads/<branch>, *destination* being the remote's only push URL.
        See the module docstring."""
        if not _FEATURE_REF_RE.fullmatch(branch) or branch in protected or not _SHA_RE.fullmatch(sha):
            raise ScopeViolationError(f"only a feature branch is ever pushed (by its full commit SHA), not {branch!r}")
        project = self._quiescent()
        try:
            with self.locks.git().acquire(timeout=self.lock_timeout):
                if self.rev_parse(f"refs/heads/{branch}") != sha:
                    raise HeadMismatchError(f"{branch} is not at the validated {sha[:12]}: the branch moved")
                if self.current_branch() != branch or self.rev_parse("HEAD") != sha:
                    raise HeadMismatchError(f"the checkout is not on {branch} at {sha[:12]}")
                unclean = self.tracked_changes() + self.untracked_files() + git_operation_in_progress(self.root)
                if unclean:
                    raise GitOperationError(f"the checkout is not clean ({unclean[:10]}); nothing is pushed")
                self._check_destination(remote, destination)
                before = self.remote_head(branch, remote=remote, timeout=timeout)
                if before == sha:
                    return PushResult(branch, sha, before, pushed=False)
                if before is not None and not (self._has_commit(before) and self.is_ancestor(before, sha)):
                    raise RemoteRejectedError(f"{remote} has {branch} at {before[:12]}, which {sha[:12]} does not "
                                              "contain: not a fast-forward, and a push is never forced")
                self._check_destination(remote, destination)  # again, right before the push
                result = self._network("push", "--porcelain", "--no-verify", remote, f"{sha}:refs/heads/{branch}",
                                       timeout=timeout)
                if result.returncode != 0:
                    refused = [line for line in result.stdout.splitlines() if line.startswith("!")]
                    if refused:
                        why = " ".join(refused[0].split())[:300]
                        raise RemoteRejectedError(f"{remote} rejected the push of {branch}: {why}")
                    raise RemoteUnavailableError(f"git push to {remote} failed: {_tail(result)}")
                after = self.remote_head(branch, remote=remote, timeout=timeout)
                if after != sha:
                    raise RemoteUnavailableError(f"after the push {remote} has {branch} at {after or 'nothing'}, not "
                                                 f"{sha[:12]}")
                return PushResult(branch, sha, before, pushed=True)
        finally:
            project.release()

    def fetch_branch(self, branch: str, *, remote: str = "origin", timeout: float = 120.0) -> str:
        """Fetch *remote*'s refs/heads/<branch> into FETCH_HEAD and return its commit (merge verification)."""
        if not _BRANCH_RE.fullmatch(branch) or ".." in branch:
            raise GitOperationError(f"invalid branch name {branch!r}")
        with self.locks.git().acquire(timeout=self.lock_timeout):
            result = self._network("fetch", "--no-tags", "--no-recurse-submodules", remote, f"refs/heads/{branch}",
                                   timeout=timeout)
            if result.returncode != 0:
                raise RemoteUnavailableError(f"git fetch {remote} {branch} failed: {_tail(result)}")
            return self.rev_parse("FETCH_HEAD")

    def _has_commit(self, sha: str) -> bool:
        return subprocess.run([*self._gitc(), "cat-file", "-e", f"{sha}^{{commit}}"], capture_output=True,
                              env=self._env(), check=False).returncode == 0

    def fast_forward_branch(self, branch: str, *, since: str, to: str, project: FileLock) -> bool:
        """Fast-forward the checked-out feature *branch* to commit *to* (fetched already) — never a reset, never a
        non-fast-forward. The branch must be at *since* or on the way from it to *to* (a re-run after an
        interruption), the checkout on it, with no tracked change and no unfinished Git operation; untracked files
        a commit would overwrite make Git refuse. The caller holds *project* (project.lock EXCLUSIVE: no writer can
        start while the working tree changes); git.lock is taken here. False: the branch is already at *to*."""
        if not _FEATURE_REF_RE.fullmatch(branch) or not _SHA_RE.fullmatch(since) or not _SHA_RE.fullmatch(to):
            raise ScopeViolationError(f"only a feature branch is fast-forwarded, to a full commit SHA, not {branch!r}")
        if not project.held or project.shared:
            raise WritersActiveError("fast-forwarding the shared checkout needs project.lock EXCLUSIVE")
        with self.locks.git().acquire(timeout=self.lock_timeout):
            assert_no_execution_config(self.root, where="the feature checkout")
            if self.current_branch() != branch:
                raise HeadMismatchError(f"the checkout is on {self.current_branch()!r}, not {branch!r}")
            local = self.rev_parse(f"refs/heads/{branch}")
            if local == to:
                return False
            if not (self.is_ancestor(since, local) and self.is_ancestor(local, to)):
                raise HeadMismatchError(f"{branch} is at {local[:12]}, not on the way from {since[:12]} to {to[:12]}: "
                                        "it is never moved there (no reset, no non-fast-forward)")
            unclean = self.tracked_changes() + git_operation_in_progress(self.root)
            if unclean:
                raise GitOperationError(f"the checkout is not clean ({unclean[:10]}); nothing is fast-forwarded")
            self._git("merge", "--ff-only", "--no-stat", "--quiet", to)
            if self.rev_parse(f"refs/heads/{branch}") != to or self.rev_parse("HEAD") != to:
                raise GitOperationError(f"after the fast-forward {branch} is not at {to[:12]}")
            return True

    # -- dry-run plans -------------------------------------------------------

    @staticmethod
    def push_plan(branch: str, remote: str = "origin") -> list[str]:
        """The non-force push the coordinator would run (never executed yet)."""
        return ["git", "push", "--set-upstream", remote, f"refs/heads/{branch}:refs/heads/{branch}"]
